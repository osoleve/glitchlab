"""Versioned local persistence for reusable typed workflows."""

from __future__ import annotations

import hashlib
import json
import re
import uuid
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from .catalog import definitions_by_kind, with_control_ports
from .models import LoomSpec, WorkflowDraft, WorkflowSpec

WORKFLOW_KIND_PREFIX = "workflow:"
WORKFLOW_KIND_PATTERN = re.compile(
    r"^workflow:(?P<workflow_id>[0-9a-f-]+):v(?P<version>[1-9][0-9]*)$"
)


class WorkflowInUseError(ValueError):
    """Raised when deletion would break another saved workflow."""

    def __init__(self, dependents: list[str]) -> None:
        self.dependents = dependents
        super().__init__(
            "Workflow is used by: " + ", ".join(dependents)
        )


def workflow_kind(workflow_id: str, version: int) -> str:
    """Return the stable node kind for one immutable workflow version."""

    return f"{WORKFLOW_KIND_PREFIX}{workflow_id}:v{version}"


def _display_binding_label(
    workflow: WorkflowSpec,
    *,
    node_id: str,
    node_port: str,
    label: str,
    direction: str,
) -> str:
    """Compact labels generated by the older node-title-plus-port convention."""

    node = next(
        (candidate for candidate in workflow.graph.nodes if candidate.id == node_id),
        None,
    )
    if node is None:
        return label
    definition = definitions_by_kind().get(node.kind)
    if definition is None:
        return label
    definition = with_control_ports(definition, node.control_ports)
    port = next(
        (
            candidate
            for candidate in definition[direction]
            if candidate["name"] == node_port
        ),
        None,
    )
    if port is None:
        return label
    node_title = node.title or definition["label"]
    legacy_label = f"{node_title} · {port['label']}"
    return port["label"] if label == legacy_label else label


def workflow_definition(workflow: WorkflowSpec) -> dict[str, Any]:
    """Expose a stored workflow through the ordinary node catalog contract."""

    return {
        "kind": workflow_kind(workflow.id, workflow.version),
        "label": workflow.name,
        "category": "Workflows",
        "description": workflow.description or f"Reusable workflow, version {workflow.version}.",
        "inputs": [
            {
                "name": binding.name,
                "label": _display_binding_label(
                    workflow,
                    node_id=binding.node_id,
                    node_port=binding.node_port,
                    label=binding.label,
                    direction="inputs",
                ),
                "type": binding.type,
                "required": binding.required,
                "multiple": binding.multiple,
            }
            for binding in workflow.inputs
        ],
        "outputs": [
            {
                "name": binding.name,
                "label": _display_binding_label(
                    workflow,
                    node_id=binding.node_id,
                    node_port=binding.node_port,
                    label=binding.label,
                    direction="outputs",
                ),
                "type": binding.type,
                "required": True,
                "multiple": False,
            }
            for binding in workflow.outputs
        ],
        "fields": [],
        "workflow": {
            "id": workflow.id,
            "version": workflow.version,
            "digest": workflow.digest,
        },
    }


class WorkflowStore:
    """Read and append immutable workflow versions under the workspace."""

    def __init__(self, workspace: Path) -> None:
        self.root = workspace.resolve() / ".glitchloom" / "workflows"

    def _records(self) -> list[WorkflowSpec]:
        if not self.root.is_dir():
            return []
        records: list[WorkflowSpec] = []
        for path in sorted(self.root.glob("*/v*.json")):
            try:
                records.append(
                    WorkflowSpec.model_validate_json(path.read_text(encoding="utf-8"))
                )
            except (OSError, ValueError):
                continue
        return records

    @staticmethod
    def _validated_id(workflow_id: str) -> str:
        try:
            parsed = uuid.UUID(workflow_id)
        except ValueError as exc:
            raise ValueError(f"Invalid workflow ID {workflow_id!r}.") from exc
        normalized = str(parsed)
        if normalized != workflow_id:
            raise ValueError(f"Invalid workflow ID {workflow_id!r}.")
        return normalized

    def list_latest(self) -> list[WorkflowSpec]:
        """Return the newest version of each named workflow."""

        latest: dict[str, WorkflowSpec] = {}
        for record in self._records():
            current = latest.get(record.id)
            if current is None or record.version > current.version:
                latest[record.id] = record
        return sorted(latest.values(), key=lambda item: item.name.casefold())

    def list_versions(self, workflow_id: str) -> list[WorkflowSpec]:
        """Return every immutable version for one workflow identity."""

        workflow_id = self._validated_id(workflow_id)
        return sorted(
            (
                record
                for record in self._records()
                if record.id == workflow_id
            ),
            key=lambda item: item.version,
        )

    def get(self, workflow_id: str, version: int) -> WorkflowSpec:
        """Load one exact immutable workflow version."""

        workflow_id = self._validated_id(workflow_id)
        path = self.root / workflow_id / f"v{version}.json"
        if not path.is_file():
            raise ValueError(f"Workflow {workflow_id!r} version {version} does not exist.")
        try:
            return WorkflowSpec.model_validate_json(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            raise ValueError(
                f"Workflow {workflow_id!r} version {version} could not be loaded."
            ) from exc

    def get_by_kind(self, kind: str) -> WorkflowSpec:
        """Resolve a workflow node kind to its exact stored record."""

        match = WORKFLOW_KIND_PATTERN.fullmatch(kind)
        if not match:
            raise ValueError(f"Invalid workflow node kind {kind!r}.")
        return self.get(match["workflow_id"], int(match["version"]))

    def definition_for_kind(self, kind: str) -> dict[str, Any]:
        """Return a catalog definition for an exact workflow node kind."""

        return workflow_definition(self.get_by_kind(kind))

    def node_definition(self, kind: str) -> dict[str, Any]:
        """Resolve either a native or reusable node definition."""

        static = definitions_by_kind().get(kind)
        if static is not None:
            return static
        return self.definition_for_kind(kind)

    def validate(self, draft: WorkflowDraft) -> None:
        """Validate workflow metadata and interface bindings without writing."""

        name = draft.name.strip()
        if not name:
            raise ValueError("Workflow name cannot be empty.")
        if not draft.graph.nodes:
            raise ValueError("A workflow must contain at least one node.")
        if not draft.outputs:
            raise ValueError("A workflow must expose at least one output.")

        nodes = {node.id: node for node in draft.graph.nodes}
        if len(nodes) != len(draft.graph.nodes):
            raise ValueError("Workflow node IDs must be unique.")

        input_names: set[str] = set()
        input_targets: set[tuple[str, str]] = set()
        for binding in draft.inputs:
            if binding.name in input_names:
                raise ValueError(f"Workflow input name {binding.name!r} is duplicated.")
            input_names.add(binding.name)
            target = (binding.node_id, binding.node_port)
            if target in input_targets:
                raise ValueError(
                    f"Workflow input target {binding.node_id}.{binding.node_port} is duplicated."
                )
            input_targets.add(target)
            node = nodes.get(binding.node_id)
            if node is None:
                raise ValueError(f"Workflow input {binding.name!r} references a missing node.")
            definition = with_control_ports(
                self.node_definition(node.kind),
                node.control_ports,
            )
            ports = {port["name"]: port for port in definition["inputs"]}
            port = ports.get(binding.node_port)
            if port is None:
                raise ValueError(
                    f"Workflow input {binding.name!r} references a missing port."
                )
            if binding.type != port["type"]:
                raise ValueError(
                    f"Workflow input {binding.name!r} declares {binding.type}, "
                    f"but its target accepts {port['type']}."
                )
            if binding.required != port["required"]:
                raise ValueError(
                    f"Workflow input {binding.name!r} has the wrong required/default state."
                )
            if binding.multiple != port["multiple"]:
                raise ValueError(
                    f"Workflow input {binding.name!r} has the wrong connection cardinality."
                )

        output_names: set[str] = set()
        for binding in draft.outputs:
            if binding.name in output_names:
                raise ValueError(f"Workflow output name {binding.name!r} is duplicated.")
            output_names.add(binding.name)
            node = nodes.get(binding.node_id)
            if node is None:
                raise ValueError(f"Workflow output {binding.name!r} references a missing node.")
            definition = with_control_ports(
                self.node_definition(node.kind),
                node.control_ports,
            )
            ports = {port["name"]: port for port in definition["outputs"]}
            port = ports.get(binding.node_port)
            if port is None:
                raise ValueError(
                    f"Workflow output {binding.name!r} references a missing port."
                )
            if binding.type != port["type"]:
                raise ValueError(
                    f"Workflow output {binding.name!r} declares {binding.type}, "
                    f"but its source emits {port['type']}."
                )

    def save(
        self,
        draft: WorkflowDraft,
        *,
        workflow_id: str | None = None,
    ) -> WorkflowSpec:
        """Append an immutable version, optionally pinning an existing identity."""

        self.validate(draft)
        normalized_name = draft.name.strip()
        latest = self.list_latest()
        named_match = next(
            (
                record
                for record in latest
                if record.name.casefold() == normalized_name.casefold()
            ),
            None,
        )
        if workflow_id is not None:
            workflow_id = self._validated_id(workflow_id)
            existing = next(
                (record for record in latest if record.id == workflow_id),
                None,
            )
            if existing is None:
                raise ValueError(f"Workflow {workflow_id!r} does not exist.")
            if named_match is not None and named_match.id != workflow_id:
                raise ValueError(
                    f"Another workflow is already named {normalized_name!r}."
                )
        else:
            existing = named_match
            workflow_id = existing.id if existing else str(uuid.uuid4())
        version = existing.version + 1 if existing else 1
        canonical = {
            **draft.model_dump(mode="json"),
            "name": normalized_name,
            "id": workflow_id,
            "version": version,
        }
        digest = hashlib.sha256(
            json.dumps(canonical, sort_keys=True, separators=(",", ":")).encode()
        ).hexdigest()
        record_data = draft.model_dump()
        record_data["name"] = normalized_name
        record = WorkflowSpec(
            **record_data,
            id=workflow_id,
            version=version,
            digest=digest,
            created_at=datetime.now(UTC).isoformat(),
        )

        directory = self.root / workflow_id
        directory.mkdir(parents=True, exist_ok=True)
        destination = directory / f"v{version}.json"
        temporary = directory / f".v{version}.{uuid.uuid4().hex}.tmp"
        temporary.write_text(
            record.model_dump_json(indent=2),
            encoding="utf-8",
        )
        temporary.replace(destination)
        return record

    def delete(self, workflow_id: str, *, force: bool = False) -> dict[str, Any]:
        """Move every version to recoverable local trash."""

        workflow_id = self._validated_id(workflow_id)
        versions = self.list_versions(workflow_id)
        if not versions:
            raise ValueError(f"Workflow {workflow_id!r} does not exist.")

        dependents: list[str] = []
        for record in self._records():
            if record.id == workflow_id:
                continue
            references_target = any(
                (
                    match := WORKFLOW_KIND_PATTERN.fullmatch(node.kind)
                ) is not None
                and match["workflow_id"] == workflow_id
                for node in record.graph.nodes
            )
            if references_target:
                dependents.append(f"{record.name} v{record.version}")
        loom_root = self.root.parent / "looms"
        if loom_root.is_dir():
            for path in sorted(loom_root.glob("*.json")):
                try:
                    loom = LoomSpec.model_validate_json(path.read_text(encoding="utf-8"))
                except (OSError, ValueError):
                    continue
                references_target = any(
                    (
                        match := WORKFLOW_KIND_PATTERN.fullmatch(node.kind)
                    ) is not None
                    and match["workflow_id"] == workflow_id
                    for node in loom.graph.nodes
                )
                if references_target:
                    dependents.append(f"Loom {loom.graph.name}")
        dependents = sorted(set(dependents))
        if dependents and not force:
            raise WorkflowInUseError(dependents)

        source = self.root / workflow_id
        trash_root = self.root / ".trash"
        trash_root.mkdir(parents=True, exist_ok=True)
        timestamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%S%fZ")
        destination = trash_root / f"{workflow_id}-{timestamp}"
        source.replace(destination)
        return {
            "id": workflow_id,
            "name": versions[-1].name,
            "versions": len(versions),
            "dependents": dependents,
            "recoverable_path": str(destination.relative_to(self.root.parent.parent)),
        }


